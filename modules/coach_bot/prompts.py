SYSTEM_PROMPTS = {
    'welcome': WELCOME_PROMPT,
    'reflection': REFLECTION_PROMPT,
    'planning': PLANNING_PROMPT,
    'tracking': TRACKING_PROMPT,
    'paywall': PAYWALL_PROMPT,
}

def get_prompt(stage: str) -> str:
    """Get system prompt for a specific stage"""
    return SYSTEM_PROMPTS.get(stage, WELCOME_PROMPT)
